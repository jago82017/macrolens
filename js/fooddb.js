const CAT_EMOJI = { fruit: '🍎', veg: '🥦', grain: '🍞', bakery: '🥐', breakfast: '🥣', dairy: '🥛', protein: '🍗', snack: '🥜', dish: '🍽️', asian: '🍜', salad: '🥗', soup: '🥣', dessert: '🍰', drink: '🥤' };
export const categoryEmoji = cat => CAT_EMOJI[cat] || '🍽️';

const titleCase = s => s.replace(/\b\w/g, c => c.toUpperCase());

export const BUILTIN_FOODS = ROWS.map(([key, name, emoji, kcal, protein, carbs, fat, fiber, g, label, category, adj]) => ({
  id: `builtin:${key}`,
  key,
  name: titleCase(name),
  label: name, // natural-language label used in AI prompts
  emoji,
  source: 'builtin',
  category,
  adj: !!adj,
  per100: { kcal, protein, carbs, fat, fiber },
  servings: [{ label, grams: g }],
}));

export const builtinById = new Map(BUILTIN_FOODS.map(f => [f.id, f]));

// Lightweight local search used by the Add Food sheet.
export function searchBuiltin(q, limit = 12) {
  const terms = q.toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  return BUILTIN_FOODS
    .map(f => {
      const n = f.label;
      if (!terms.every(t => n.includes(t))) return null;
      let score = 1;
      if (n.startsWith(terms[0])) score += 2;
      if (n === terms.join(' ')) score += 5;
      return { f, score: score - n.length / 100 };
    })
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(x => x.f);
}
